// Assemble __ASSETS_DIR__/ — the only files the Worker serves — from the repo.
//
// Deliberately an allowlist, not "everything except". A repo usually holds
// sources, scripts, exports, docs and tooling that do not belong behind the
// site's URL. Add a path here on purpose.
//
// Refuses to build if any listed HTML page has lost its noindex tag: the site
// is unlisted, and that tag is one of the things (with robots.txt and the
// Worker's X-Robots-Tag header) that keeps it out of search engines. Delete
// the check if the site is meant to be indexed once the gate comes off.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, '__ASSETS_DIR__');

// Files and directories, relative to the repo root. Generated by the scaffold;
// edit freely.
const served = __SERVED__;

const NOINDEX = /<meta\s+name="robots"\s+content="noindex,\s*nofollow"\s*\/?>/iu;
for (const entry of served.filter((path) => path.endsWith('.html'))) {
  const html = readFileSync(join(root, entry), 'utf8');
  if (!NOINDEX.test(html)) {
    console.error(`build-site: ${entry} has no <meta name="robots" content="noindex, nofollow"> — refusing to build.`);
    process.exit(1);
  }
}

rmSync(dist, { force: true, recursive: true });
mkdirSync(dist, { recursive: true });

let files = 0;
let bytes = 0;
for (const entry of served) {
  const from = join(root, entry);
  if (!existsSync(from)) {
    console.error(`build-site: expected ${entry} to exist.`);
    process.exit(1);
  }
  const to = join(dist, entry);
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to, {
    recursive: true,
    filter: (source) => {
      const name = source.split('/').pop();
      if (name === '.DS_Store') return false;
      const info = statSync(source);
      if (info.isFile()) {
        files += 1;
        bytes += info.size;
      }
      return true;
    },
  });
}

console.log(`build-site: ${files} files, ${(bytes / 1024 / 1024).toFixed(1)} MB → __ASSETS_DIR__/`);
